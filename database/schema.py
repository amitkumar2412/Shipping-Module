MSD_INSERT = (
    "INSERT INTO mainshipdata ({cols}, synced_at) VALUES ({placeholders}, %(synced_at)s) "
    "ON CONFLICT (vessel_ship_id) DO UPDATE SET {updates}, synced_at=EXCLUDED.synced_at"
).format(
    cols=", ".join(MSD_COLS),
    placeholders=", ".join(f"%({c})s" for c in MSD_COLS),
    updates=", ".join(f"{c}=EXCLUDED.{c}" for c in MSD_COLS if c != "vessel_ship_id"),
)
